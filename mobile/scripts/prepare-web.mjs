import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../../public/mobile/',import.meta.url);
const logic=(await Promise.all(['logic.js','follow.js','studio.js','pitch.js','score-io.js','music-tools.js'].map(async name=>(await readFile(new URL(name,base),'utf8')).replace(/^import[^\n]+\n/gm,'').replace(/^export /gm,'')))).join('\n');
const app=(await readFile(new URL('app.js',base),'utf8')).replace(/^import[^\n]+\n/,'');
await writeFile(new URL('bundle.js',base),'// Generated by mobile/scripts/prepare-web.mjs.\n(()=>{\n"use strict";\n'+logic+'\n'+app+'\n})();\n');
console.log('Mobile UI bundled for Android, iOS and web preview.');
